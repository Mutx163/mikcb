# Map ARB filenames to locale keys
ARB_FILES = {
    "app_zh.arb": "zh",
    "app_en.arb": "en",
    "app_ja.arb": "ja",
    "app_ko.arb": "ko",
    "app_zh_HK.arb": "zh_HK",
    "app_zh_TW.arb": "zh_TW",
}


def main():
    for arb_file, locale_key in ARB_FILES.items():
        path = os.path.join(L10N_DIR, arb_file)
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)

        if locale_key == "zh":
            translations = NEW_ENTRIES_ZH
        else:
            translations = TRANSLATIONS[locale_key]

        added = 0
        skipped = 0
        for key, value in translations.items():
            if key in data:
                skipped += 1
                continue
            data[key] = value
            added += 1

        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

        print(f"{arb_file}: added {added}, skipped {skipped} (already exist)")


if __name__ == "__main__":
    main()
