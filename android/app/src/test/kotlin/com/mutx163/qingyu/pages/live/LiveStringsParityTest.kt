package com.mutx163.qingyu.pages.live

import com.mutx163.qingyu.core.MiniJson
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * 实时活动与超级岛文案逐字对照 ARB（`lib/l10n/app_zh.arb`）。
 *
 * 验收门槛 3：界面文案与 ARB 原文逐字一致，不自己改写、不省略占位符。
 */
class LiveStringsParityTest {

    private val arbMap: Map<String, String> by lazy { loadArbZh() }

    @Test
    fun `每一处屏上文案都与 app_zh_arb 逐字一致`() {
        val texts = LiveStrings.allTexts
        assertTrue("文案条数不应少于 30 条，当前 ${texts.size}", texts.size >= 30)

        for (item in texts) {
            val template = arbMap[item.key]
            assertTrue("ARB(app_zh.arb) 中缺少键 `${item.key}`", template != null)
            assertMatchesArb(item.key, item.zh, template!!)
        }
    }

    @Test
    fun `格式化函数输出符合预期`() {
        assertEquals("20 分钟", LiveStrings.formatBeforeClassMinutes(20))
        assertEquals("距上课 15:00", LiveStrings.formatUntilClassStart("15:00"))
        assertEquals("距下课 45:00", LiveStrings.formatUntilClassEnd("45:00"))
        assertEquals("02:05", LiveStrings.formatCountdown(125))
        assertEquals("00:00", LiveStrings.formatCountdown(0))
        assertEquals("00:00", LiveStrings.formatCountdown(-10))
        assertEquals("提前 15 分钟", LiveStrings.formatLeadMinutes(15))
        assertEquals("下课后保留 10 分钟", LiveStrings.formatKeepMinutes(10))
        assertEquals("不驻留（立即结束）", LiveStrings.formatKeepMinutes(0))
    }

    private fun assertMatchesArb(key: String, text: String, template: String) {
        if (!template.contains('{')) {
            assertEquals("ARB 键 `$key` 的屏上文案与 arb 不一致", template, text)
            return
        }
        val segments = template.split(Regex("""\{[^}]*\}""")).filter { it.isNotEmpty() }
        var cursor = 0
        for (segment in segments) {
            val idx = text.indexOf(segment, cursor)
            assertTrue(
                "键 `$key` 的渲染值『$text』里找不到模板片段『$segment』（模板：$template）",
                idx >= 0,
            )
            cursor = idx + segment.length
        }
    }

    private fun loadArbZh(): Map<String, String> {
        var dir: File? = File("").absoluteFile
        var arbFile: File? = null
        repeat(8) {
            val candidate = File(dir, "lib/l10n/app_zh.arb")
            if (candidate.isFile) {
                arbFile = candidate
                return@repeat
            }
            dir = dir?.parentFile
        }
        val file = arbFile ?: error("找不到 lib/l10n/app_zh.arb")
        val parsed = MiniJson.parse(file.readText(Charsets.UTF_8))
        check(parsed is Map<*, *>) { "app_zh.arb 顶层不是对象：${file.absolutePath}" }
        val map = LinkedHashMap<String, String>()
        parsed.forEach { (k, v) -> if (k is String && v is String) map[k] = v }
        return map
    }
}
