/// 日视图议程卡「正在进行」进度条的量化（2026-10-24 从 `timetable_screen.dart`
/// 的私有静态方法搬出 —— 主文件与日视图分片共用一条行数棘轮，只减不增）。
///
/// ## 为什么必须量化，而不是直接用原始比值
///
/// 原始比值带**秒级**精度，而进度是每秒 tick 一次重算的：不量化的话每一 tick
/// 都会让进度补间重新定位（retarget），补间永远走不完 ⇒ 日视图每秒都在动画、
/// 每帧都在重烤它那一大片玻璃材质，永不停歇。
///
/// 量化到 250 档（≈0.4%，满宽卡上约 1.5px）在观感上分辨不出来，但补间能在两次
/// tick 之间走完，静止时不再排帧。
///
/// ## 上下限为什么是 0.02 / 0.98
///
/// 不是审美：进度条为 0 时那一格高度为 0，带圆角的胶囊会画成一个破口；为 1 时
/// 同理贴死右端。两端各留一档让胶囊始终是个完整的圆角条。
library;

/// 把 [raw]（0..1 的原始进度）折算成分档后的进度。
double quantizeDayAgendaProgress(double raw) {
  const steps = 250;
  return ((raw * steps).floorToDouble() / steps).clamp(0.02, 0.98);
}
