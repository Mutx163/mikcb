/// 月视图的**字阶与栅格**：整页只有一个真源。
///
/// ## 为什么必须收在一处
///
/// 2026-10-21 的专业评审量了真机截图：这一页同时用了 **9 级字号**
/// （9 / 9.5 / 11 / 11.5 / 12 / 12.5 / 13 / 13.5 / 14 / 15 / 16 / 17 / 21），
/// 其中 11.5、9.5、13.5 这类半像素值与任何一级都不成比例 —— 层级因此不可预期。
/// 左边线同样有四条（11.7 / 13.5 / 14.1 / 17.2），四条都差 1~5dp。
///
/// 所以字阶只留四级（caption / body / title / display）加两个专用值，
/// 径向栅格由 [MonthMetrics] 一处定义。
///
/// ## 2026-10-25：那四级本身也不合格（第二次数）
///
/// 上一轮把 9 级收成 4 级，但收出来的四级是 **11 / 12 / 13 / 14**：相邻只差
/// 1px、比例 1.08，人眼在真机上看不出层级。这一轮改成五级、相邻比 ≥1.15
/// （见 [MonthType] 那张表），并把散着的 15 个 alpha 收成 5 档（见 [MonthInk]）。
///
/// **教训**：把"级数变少"当成目标是不够的 —— 判据是**相邻级的比值**，
/// 只数级数会把 11/12/13/14 这种"看着是四级、读起来是一级"的阶梯放过去。
///
/// ## 一条被实测否决的评审建议（留档，别再重走）
///
/// 评审第 P2 条建议「收起时把品牌行折进玻璃带，把那 44dp 还给网格」。
/// 实测（2026-10-21，393×851）证明**它换不到任何可读性收益**：
///
/// * 格子行高按**宽度**定（目标是正方形，见 `monthGridRowHeight`）：
///   `(393 − 2×12.5 − 40) / 7 = 47.43dp`，而按高度预算能给的也正好是
///   47.43 —— 上限由屏宽决定，不由高度决定；
/// * 于是把 44dp 还给正文后，行高一点不变，多出来的高度全进了面板
///   （实测 390dp → 434dp），而面板本来就有 58% 的行没有内容。
///
/// 同时它会破坏两件真东西：品牌行与右上角玻璃球共用 `TimetableTitleBar`
/// （首页同一份实现），折走会让独立页与首页的顶栏高度分家 —— 那正是
/// 2026-10-20 用户报「为什么和日视图周视图的顶栏不一样高」的原事故。
///
/// ⇒ 竖向空间该从**面板内部**省，不在顶部那两行。
library;

/// 月视图的字号阶梯。
///
/// ## 2026-10-25：阶梯重做（旧阶梯人眼分不出级）
///
/// 旧阶梯是 11 / 12 / 13 / 14 一路排下来，**相邻只差 1px、比例 1.08** ——
/// 真机截图里"表头、副行、卡标题、日期数字"四种文字读起来是同一个大小，
/// 层级等于不存在，整页因此糊成一片（用户 2026-10-25 说"看起来非常难受"的
/// 结构性成因之一，见 `test/services/month_view_aesthetic_contract_test.dart`）。
///
/// 新阶梯**只留五级、相邻比一律 ≥1.15**：
///
/// | 级 | 值 | 相邻比 | 用途 |
/// |---|---|---|---|
/// | [caption] | 11 | — | 星期表头、统计标签、角标、注脚 |
/// | [body] | 13 | 1.18 | 副行、空态说明、按钮文字、年份 |
/// | [title] | 15 | 1.15 | 卡标题、分区标题、议程行标题 |
/// | [dayNumber] | 18 | 1.20 | 日期数字（格子的主体） |
/// | [display] | 22 | 1.22 | 概览大数字、工具行的月份 |
///
/// [ladder] 是这份阶梯的**机器可读形式**：守卫按它逐级验比例，别在测试里
/// 另抄一份数组（抄了就会漂）。
///
/// ## 唯一的例外：[rail]
///
/// 周次轨（`第 17 周`）的列宽被 40dp 卡死，只能取 10 —— 它**不属于**上面那条
/// 阶梯，因此也不参与比例守卫。这是空间约束，不是审美选择：11 会让 `第 17 周`
/// 在 40dp 里折成两行（见 [MonthMetrics] 里那条历史记录）。
abstract final class MonthType {
  /// 最小一级：星期表头、统计标签、角标、注脚。
  static const double caption = 11;

  /// 正文/副标题：卡片副行、空态说明、按钮文字、工具行的年份。
  static const double body = 13;

  /// 标题级：分区标题、卡片标题、当日议程的行标题。
  static const double title = 15;

  /// 日期数字（网格格子里）—— 格子的主体，比 [title] 大一级。
  ///
  /// 18 而不是旧的 14：格子约 47dp 见方，14 在里面显得空、字重也压不住色带；
  /// 18 与 [title] 的比例是 1.20，落在阶梯口径内。
  static const double dayNumber = 18;

  /// 展示级：本月概览的三个大数字，**也是**工具行的月份（`10月`）。
  ///
  /// 两者共用一档是有意的：它们从不同屏（月份在日历卡顶、大数字在信息卡里），
  /// 而 22 对两者都合适；再拆一档就会把阶梯撑到 6 级以上、比例也压不住。
  static const double display = 22;

  /// 周次轨（`第 17 周`）。**阶梯之外的专用值**（宽度被 40dp 的窄列卡着）；
  /// 必须配合 `maxLines: 1` + `FittedBox` 使用，否则会折成两行。
  static const double rail = 10;

  /// 阶梯本体（小 → 大）。守卫按它逐级验「相邻比 ≥1.15」与「级数 ≤6」。
  static const List<double> ladder = <double>[
    caption,
    body,
    title,
    dayNumber,
    display,
  ];
}

/// 月视图的**墨色档**：只留五档，每档一个明确语义。
///
/// ## 2026-10-25：从 15 档散值收敛成 5 档
///
/// 旧实现里散着 15 个 alpha（0.06 / 0.08 / 0.10 / 0.18 / 0.20 / 0.30 / 0.38 /
/// 0.42 / 0.55 / 0.62 / 0.66 / 0.70 / 0.72 / 0.78 / 0.80）。其中 0.55 / 0.62 /
/// 0.66 / 0.70 / 0.72 **五档几乎看不出差别**，却分别用在"表头、副行、注脚、
/// 箭头"四种不同语义上 —— 语义没分级，级差却白占了五档。
///
/// 更实际的问题在对比度：0.38 与 0.42 压在卡面上只有 **2.34:1 / 2.60:1**，
/// 低于 3:1 这条底线，箭头与空态图标基本靠猜（按浅色主题 surface 实测）。
///
/// 现在五档各司其职，且**文字只允许用前三档**（对比度 6.14 / 4.75 / 3.79，
/// 全部 ≥3:1）；[hairline] 与 [fill] 是**非文字**档，用于分隔线、拉杆与卡内
/// 色块底 —— 拿它们写字就是踩 3:1 那条线。
abstract final class MonthInk {
  /// 主文字：日期数字、卡标题、议程行标题。即主题 `onSurface` 原色。
  static const double primary = 1;

  /// 副行 / 说明：卡内副标题、空态正文、日期摘要（对比度 6.14:1）。
  static const double secondary = 0.70;

  /// 表头 / 注脚 / 图标：星期表头、统计标签、「还有 N 天」、箭头
  /// （对比度 3.79:1，**文字能用的最低一档**）。
  static const double tertiary = 0.55;

  /// **非文字**：分隔线、卡底拉杆、装饰描边。
  static const double hairline = 0.12;

  /// **非文字**：卡内色块底（日期筹码、今天药丸、分区底）。
  static const double fill = 0.06;

  /// 五档本体（深 → 浅）。守卫按它验「档数 ≤5」与「文字档对比度 ≥3:1」。
  static const List<double> levels = <double>[
    primary,
    secondary,
    tertiary,
    hairline,
    fill,
  ];

  /// 可以拿来写字的档（对比度均 ≥3:1）。[hairline] / [fill] 不在其中。
  static const List<double> textLevels = <double>[
    primary,
    secondary,
    tertiary,
  ];
}

/// 月视图的栅格与间距。
///
/// ## 2026-10-23：从「一整块白色面板」改成「一组独立卡片」
///
/// 用户拿着小米日历的截图提了两条口径：
/// 1. 「拉杆区域，还有框框区域像这样」—— 日历本身是一张**白色圆角卡片**，
///    拉杆是这张卡**底部中央**那根小横条；
/// 2. 「下面的信息区域也改成这样，单独的卡片，而不是一个整体大卡片」——
///    信息区不再是一整块铺满下半屏的白板，而是**一张张分开的卡**。
///
/// 于是版面从「壁纸 + 白板 + 板内灰卡」变成「壁纸 + 白卡 + 白卡」：日历卡与
/// 信息卡都直接浮在壁纸上、共用同一条外沿 [cardInset]，与周视图 / 日视图的
/// 课程卡同一套语言（这也是用户 2026-10-20 说过「月视图应该跟周视图、日视图
/// 保持一致风格」的延伸）。
///
/// ## 唯一的左轴是「文字墨迹」那条线
///
/// | 层 | 位置 |
/// |---|---|
/// | 卡片外沿 | [cardInset] = 8 |
/// | 卡片内边距 | [cardPadding] = 14 |
/// | **文字墨迹（左轴）** | [axisInset] = 22 |
///
/// 日历卡里的格子是**居中**的，所以格子的填充边比外沿再让 [cellGap]，
/// 让第一列日期数字的墨迹同样落在 22 上。
///
/// ⚠️ **卡是实底的**：卡片不透壁纸，所以卡片里的字一律按**主题**判（不按壁纸
/// 亮度）。2026-10-21 那套「逐行壁纸亮度判墨」是为"字直接压在壁纸上"设计的，
/// 现在格子躺在白卡上，它不再适用 —— 详见 `month_day_cell.dart` 的注释。
abstract final class MonthMetrics {
  /// **卡片外沿**：日历卡与信息卡距离屏幕左右的距离（同一条线）。
  ///
  /// 旧版面里日历格子几乎贴到屏幕边（内边距 10.5），下面那块白板却铺满整宽 ——
  /// 两种边线不可能对齐。现在两种卡共用这一个外沿。
  static const double cardInset = 8;

  /// 卡片**内部**的文字内边距。
  static const double cardPadding = 14;

  /// **唯一的左轴**：品牌名、日期数字、信息卡标题全部落在这条线上。
  ///
  /// 由 `cardInset + cardPadding` 推出来，不另写一个数：外沿一改，轴跟着走。
  static const double axisInset = cardInset + cardPadding;

  /// 卡片之间、格子之间的缝。
  static const double cellGap = 1.5;

  /// 工具行左右的内边距。
  ///
  /// ⚠️ 旧实现**左边距 0.9dp、右边距 5.2dp**（真机实测）：两个箭头直接挂在
  /// Row 两端，而尾部「今天」药丸是居中在一个 56dp 的定宽槽位里 —— 于是左边
  /// 顶着屏幕边、右边却空出 5dp，整行读起来是歪的。
  ///
  /// 取 6 而不是 [axisInset]：箭头是 40dp 的圆钮，里面那枚 22dp 的图标居中后
  /// 左沿天然比按钮左沿内缩 9dp —— 按钮左沿 6 + 图标内缩 9 = 15，与品牌名那根
  /// 竖轴接近（"圆钮对齐"对的是图标，不是按钮外框）。
  static const double toolbarInset = 6;

  /// 网格左右内边距（**从屏幕边量起**）= 外沿 + 内边距 − 格缝。
  ///
  /// 减掉 [cellGap] 是因为每个格子自己还带一圈 `Padding(cellGap)`：两者相加
  /// 正好让**格子填充边**落在 [axisInset] 上。
  ///
  /// 调用方算「格宽 = (可用宽 − 左右内边距 − 周次列) / 7」时必须用它 ——
  /// 它量的是格子实际占到的宽度。
  static const double gridHorizontalPadding = axisInset - cellGap;

  /// 日历卡**内部**的左右内边距（从卡片边缘到第一列）。
  ///
  /// ⚠️ 必须等于 `gridHorizontalPadding − cardInset`，**不能写成 cellGap**：
  /// 2026-10-23 第一版把这里写成 1.5，结果表头「周一」与周次列紧贴卡片边缘，
  /// 24dp 圆角的白卡看起来像"内容溢出的图片被裁了一刀" —— 用户说的"非常诡异"
  /// 有一半来自这里。而且它与 `monthGridRowHeight` 的宽度预算必须同源，
  /// 否则算出来的"正方形行高"会偏。
  static const double gridInnerPadding = gridHorizontalPadding - cardInset;

  /// 分区之间（概览卡 → 「本月有安排的日子」）的竖向间距。
  static const double sectionGap = 18;

  /// 分区标题与它下面第一张卡之间。
  static const double sectionTitleGap = 8;

  /// 信息卡与卡之间的缝。
  ///
  /// 8 → 10（2026-10-23）：信息区不再是白板，卡片之间露出的是**壁纸**，
  /// 缝太窄会读成"一整块被切开"；10dp 才看得出这是两张独立的卡。
  static const double itemGap = 10;

  /// 同一张卡内、两行议程之间的间距。
  ///
  /// 比 [itemGap] 小：它们共享同一张卡，读作"同一组"，靠间距分组而不是靠
  /// 再画一张卡（2026-10-23：一块卡包住标题 + 若干行，与小米日历同构）。
  static const double rowGap = 10;

  /// 日期格**底边分段色带**的高度（2026-10-22）。
  ///
  /// 取代原来的圆点行。换掉的理由是**宽度**：
  /// 一格实测 43.86dp、内容区 40.43dp，5 个圆点要 55dp、4 个要 44dp ——
  /// 分别溢出 14.57dp 与 3.57dp（2026-10-22 在真机宽度下量的）。
  /// 色带按格宽均分，段数再多也只是变窄，**永远不会溢出**。
  ///
  /// 顺序与含义不变：课程色（最多 4 段）→ 考试红 → 日程蓝。
  static const double cellStripHeight = 3;

  /// 日期数字与色带之间的间距（[MonthDayCell] 里那段 `SizedBox`）。
  static const double dayNumberStripGap = 5;

  /// **色带槽位**的高度：无论这一格有没有色带，都占同样的高。
  ///
  /// ## 为什么必须恒定占位（2026-10-25 修的那个"高低不齐"）
  ///
  /// 旧实现把「日号 + 5dp + 色带」作为一个整体在格子里**垂直居中**，而色带是
  /// `if (showStrips)` 条件渲染的。于是同一行里：
  ///
  /// * 有课的那天，内容高 = 日号 + 5 + 3，居中后日号偏上；
  /// * 没课的那天，内容只有日号，居中后日号偏下。
  ///
  /// 真机截图逐像素量出来，同一行 7 个数字的顶边在 **271 / 275** 之间跳，
  /// 离散 **4px**（`test/services/month_view_aesthetic_contract_test.dart`
  /// 里那条对齐断言就是钉这个数）。一行数字高低错落，眼睛会一直去找那条
  /// 并不存在的基准线 —— 这正是用户说的"看着难受"最直接的来源。
  ///
  /// 修法不是"把色带也画到没课的日子上"（那是往界面里加假信息），而是让
  /// 色带槽位**恒在**：无色带时留空但高度不变，所有格子内容等高、居中后
  /// 日号自然落在同一条线上（离散 0px）。
  static const double cellStripSlotHeight = dayNumberStripGap + cellStripHeight;

  /// 日期格内边距（横向）。
  ///
  /// 与 [cellGap] 是两件事：后者是**格子之间**的缝，这个是格子**内部**的留白。
  /// 色带要贴到格子左右内沿（[cellRadius] 的圆角由 `ClipRRect` 削掉），所以
  /// 这个值越小色带越长；但它同时是日期数字到格子边缘的距离。
  static const double cellInnerPadding = 2;

  /// 信息卡圆角（与日视图议程卡同档）。
  static const double cardRadius = 20;

  /// 卡片投影的强度（上下两种卡共用一档）。
  ///
  /// ⚠️ 它与 [MonthInk] 的档位是**两回事**：墨色档描述"字压在卡面上的浓度"，
  /// 这个是卡影。之所以也收成常量，是为了让"月视图里不许出现裸 alpha 字面量"
  /// 这条守卫能机械执行 —— 一旦允许裸值，墨色档就会慢慢重新散开
  /// （2026-10-25 之前正是散成 15 档）。
  static const double cardShadowAlpha = 0.06;

  /// 日历卡的圆角：比信息卡再大一级，读作「这块是一整张表」。
  ///
  /// 小米日历那类系统日历的白卡圆角约 24：比里面的日期格（[cellRadius] 12）
  /// 大一档，层级才分得开（外大内小）。
  static const double calendarCardRadius = 24;

  /// 日期格圆角。
  ///
  /// 比信息卡小得多：格子只有 ~44dp 见方，[cardRadius] 的 20 会把它削成圆形
  /// （那正是旧实现看起来像"一排药丸"的原因）。
  static const double cellRadius = 12;

  /// 信息区底部的留白（玻璃坞药丸悬在它上面）。
  ///
  /// 旧实现靠一条「从面板底色到透明」的渐隐带盖住被药丸切开的内容 —— 那需要
  /// 一块**不透明底板**才成立。现在信息区是壁纸 + 独立卡，没有板可渐隐，
  /// 改为**多留一段滚动余量**：滚到底时最后一张卡完整落在药丸上方。
  static const double panelBottomInset = 28;

  /// 「本月有安排的日子」**一行**占的高度（不含 [rowGap]）。
  ///
  /// 实测（2026-10-25，393×851）：那一列卡内 3 行占 133dp，即每行 44.3dp
  /// （行内 = 周几筹码 7+7 内边距 + 两行文字，行间 [rowGap] 10）。
  ///
  /// 它存在的唯一理由是**按可用高度反推能列几行** —— 收起网格后日历变矮、
  /// 这里应该多列几行，而不是把腾出来的空间留成空白（旧实现固定 3 行，
  /// 收起态实测空出 **304px = 35.7% 屏高**）。
  static const double upcomingRowHeight = 44;

  /// 日历卡底部拉杆区的高度（拖拽命中高度）。
  ///
  /// 视觉上只是中央那根 5dp 的小横条，但命中区别做成 5dp —— 手指点不中。
  static const double calendarHandleHeight = 26;

  /// 日历卡**卡顶导航行**的高度（`‹ 2026年10月 › 今天`）。
  ///
  /// 取 40 = 月视图工具行的历史高度，也等于周/日视图的星期栏高度。
  /// 2026-10-23 把导航从玻璃带移进日历卡时**刻意保留这个数**：改变它会让
  /// 三个视图的顶栏高度分家（用户 2026-10-20 报过「为什么和日视图周视图的
  /// 顶栏不一样高」）。
  static const double calendarNavHeight = 40;
}
