  function detectLang() {
    const params = new URLSearchParams(window.location.search);
    const forced = (params.get('lang') || '').toLowerCase();
    if (forced && I18N[forced]) return forced;
    const browser = (navigator.language || 'zh').toLowerCase();
    if (browser.startsWith('zh')) return 'zh';
    if (browser.startsWith('ja')) return 'ja';
    if (browser.startsWith('ko')) return 'ko';
    return 'en';
  }

  let currentLang = detectLang();

  function t(key, ...args) {
    const table = I18N[currentLang] || I18N.zh;
    let text = table[key] ?? I18N.en[key] ?? I18N.zh[key] ?? key;
    args.forEach((arg, index) => {
      text = text.replace(`{${index}}`, String(arg));
    });
    return text;
  }

  function applyDomI18n(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      if (key) el.setAttribute('aria-label', t(key));
    });
    document.title = t('pageTitle');
    document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : currentLang;
  }

  window.LanEditI18n = { t, applyDomI18n, getLang: () => currentLang };
  document.addEventListener('DOMContentLoaded', () => applyDomI18n());
